#!/bin/bash
# Original generation recipe of the paper, kept verbatim except that the cluster root is now ${AF_INPUT} (config.sh).
# run_grid_search_msa_config.sh
#
# This script performs a full grid search over all mutation-related parameters used by
# rna_msa_generator_base_pair.py. For each configuration the script creates a top-level folder
# with a shortname (e.g. config0, config1, …) in the output base directory. In each configuration folder,
# one subdirectory is created per input dataset (the datasets are read from files named <pdb_id>_data.json
# in the input directory). In each dataset subdirectory exactly one JSON file is generated by the MSA generator.
#
# In addition, all configuration settings are saved (one JSON per config) in a separate directory so that you can look them up later.
#
# The final structure is:
#   <output_base_dir>/
#     config0/
#       0/       <-- output for the 1st dataset (pdb file #0)
#       1/       <-- output for the 2nd dataset, etc.
#       ...
#     config1/
#       0/
#       1/
#       ...
#   <output_base_dir>/config_definitions/  (contains config0.json, config1.json, etc.)
#
# Later you can run an algorithm as, for example:
#   python algorithm --input_dir basedir/config0/<slurm_jobarray_index>
#
# where <slurm_jobarray_index> is the index of the dataset (0 to number_of_datasets-1).

#################################
# Fixed Directories and Parameters
#################################

# Directory containing input JSON files (expected to be named like <pdb_id>_data.json)
input_json_dir="${AF_INPUT:?set AF_INPUT (see config.sh)}/controlled_interventions_6WJS"

# Base directory where all grid search output will be stored.
output_base_dir="${AF_INPUT:?set AF_INPUT (see config.sh)}/6WJS_intervention_scaling_sweep_config80_$1"
mkdir -p "$output_base_dir"

# Directory to store configuration definitions.
config_def_dir="${output_base_dir}/config_definitions"
mkdir -p "$config_def_dir"

# Fixed parameters (which do not vary during the grid search):
structure_predictor=$1  # Must be one of the options accepted by the MSA generator.
seed=42
N=10  # Number of sequences generated in the MSA
max_chains=1000                    # Maximum chains allowed from the input JSON
# Optional plotting flags:
# plot_flag="--plot"
plot_flag=""
# show_plot_flag="--show_plot"
show_plot_flag=""

#################################
# Grid Search Parameter Ranges (all 10 parameters)
#################################
# (Adjust the arrays below for your hyperparameter search)
insertion_prob_loop_vals=(0.2)
deletion_prob_loop_vals=(0.8)
insertion_prob_stem_vals=(0.005)
deletion_prob_stem_vals=(0.005)
wobble_prob_vals=(0.1)
long_insertion_prob_vals=(0.1)
long_deletion_prob_vals=(0.05)
max_insertion_fraction_vals=(0.1)
max_deletion_fraction_vals=(0.1)
stem_keep_prob_vals=(0.99)

#################################
# Get list of input JSON files
#################################
# We sort the files to ensure reproducible ordering.
mapfile -t data_files < <(find "$input_json_dir" -maxdepth 1 -type f -name "*_data.json" | sort)
num_datasets=${#data_files[@]}
echo "Found ${num_datasets} input JSON files (datasets)."

#################################
# Grid Search Loop over all hyperparameter combinations
#################################
config_counter=80
# Loop over each value for insertion_prob_loop_vals (can serve as top-level config groups)
for ins_prob_loop in "${insertion_prob_loop_vals[@]}"; do
  for del_prob_loop in "${deletion_prob_loop_vals[@]}"; do
    for ins_prob_stem in "${insertion_prob_stem_vals[@]}"; do
      for del_prob_stem in "${deletion_prob_stem_vals[@]}"; do
        for wobble_prob in "${wobble_prob_vals[@]}"; do
          for long_ins in "${long_insertion_prob_vals[@]}"; do
            for long_del in "${long_deletion_prob_vals[@]}"; do
              for max_ins_frac in "${max_insertion_fraction_vals[@]}"; do
                for max_del_frac in "${max_deletion_fraction_vals[@]}"; do
                  for stem_keep in "${stem_keep_prob_vals[@]}"; do

                    # Define configuration short name.
                    config_name="config${config_counter}"
                    config_dir="${output_base_dir}/${config_name}"
                    mkdir -p "$config_dir"

                    # Save the configuration as a JSON file in the config definitions dir.
                    config_json_file="${config_def_dir}/${config_name}.json"
                    cat > "$config_json_file" <<EOF
{
  "structure_predictor": "${structure_predictor}",
  "insertion_prob_loop": ${ins_prob_loop},
  "deletion_prob_loop": ${del_prob_loop},
  "insertion_prob_stem": ${ins_prob_stem},
  "deletion_prob_stem": ${del_prob_stem},
  "wobble_prob": ${wobble_prob},
  "long_insertion_prob": ${long_ins},
  "long_deletion_prob": ${long_del},
  "max_insertion_fraction": ${max_ins_frac},
  "max_deletion_fraction": ${max_del_frac},
  "stem_keep_prob": ${stem_keep},
  "seed": ${seed},
  "N": ${N},
  "max_chains": ${max_chains}
}
EOF

                    echo "Generated ${config_name} with parameters:"
                    echo "  insertion_prob_loop=${ins_prob_loop}, deletion_prob_loop=${del_prob_loop}, insertion_prob_stem=${ins_prob_stem}, deletion_prob_stem=${del_prob_stem}"
                    echo "  wobble_prob=${wobble_prob}, long_insertion_prob=${long_ins}, long_deletion_prob=${long_del}"
                    echo "  max_insertion_fraction=${max_ins_frac}, max_deletion_fraction=${max_del_frac}, stem_keep_prob=${stem_keep}"
                    
                    # For each dataset (input JSON file) assign a subdirectory (named as a number from 0 to num_datasets-1)
                    for (( idx=0; idx< num_datasets; idx++ )); do
                      data_json_path="${data_files[$idx]}"
                      # Create subdirectory inside the current config folder.
                      dataset_subdir="${config_dir}/${idx}"
                      mkdir -p "$dataset_subdir"
                      # Extract the pdb id from filename (if desired) – here we do not use it for naming the subdir.
                      filename=$(basename "$data_json_path")
                      pdb_id="${filename%%_data.json}"
                      echo "   [${config_name}] Processing dataset index ${idx} (pdb_id=${pdb_id})"
                      
                      python rna_msa_generator_base_pair.py \
                        --structure_predictor "$structure_predictor" \
                        --pdb_id "$pdb_id" \
                        --seed "$seed" \
                        --output_json_dir "$dataset_subdir" \
                        -N "$N" \
                        --insertion-prob-loop "$ins_prob_loop" \
                        --deletion-prob-loop "$del_prob_loop" \
                        --insertion-prob-stem "$ins_prob_stem" \
                        --deletion-prob-stem "$del_prob_stem" \
                        --wobble-prob "$wobble_prob" \
                        --long-insertion-prob "$long_ins" \
                        --long-deletion-prob "$long_del" \
                        --max-insertion-fraction "$max_ins_frac" \
                        --max-deletion-fraction "$max_del_frac" \
                        --stem-keep-prob "$stem_keep" \
                        --input_json_path "$data_json_path" \
                        $plot_flag $show_plot_flag
                      # In each dataset_subdir one JSON should be generated.
                    done

                    # Increment configuration counter.
                    ((config_counter++))
                  done
                done
              done
            done
          done
        done
      done
    done
  done
done

echo ""
echo "✅ Grid search completed."
echo "Output structure:"
echo "  Each configuration directory (e.g. ${output_base_dir}/configX/) contains subdirectories numbered 0 to $((num_datasets-1))"
echo "  Each subdirectory contains one JSON file from the MSA generator for the corresponding dataset."
echo "Configuration definitions are stored in: ${config_def_dir}"
echo ""
echo "Later you can run your algorithm as:"
echo "  python algorithm --input_dir <basedir>/<config_shortname>/<slurm_jobarray_index>"
